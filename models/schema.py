from pydantic import BaseModel, Field
from typing import Annotated, Literal,Optional
from operator import add


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        ..., description="List of messages exchanged with the agent"
    )
    user_query: str = Field(
        ..., description="The original query provided by the user to the agent"
    )
    curated_prompt: str = Field(
        ...,
        description="The curated or enhanced prompt to better explain users query to the agent",
    )
    context_prompt_query: str = Field(
        ...,
        description="The context prompt containing the context related to users query to the agent",
    )
    generated_sql_query: str = Field(
        ...,
        description="The generated SQL query based on the users query and context to the agent",
    )
    is_safe: Literal["Yes", "No"] = Field(
        ...,
        description="Indicates whether the generated SQL query is safe to execute or not. If None means guard has not decided the safetyness for the generated query",
    )
    comments: str = Field(
        ...,
        description="Reasons or feedbacks that LLM provides wheather the SQL query is safe or not.",
    )
    sql_query_execution_result: str = Field(
        ..., description="The result of executing the generated SQL query"
    )
    final_response: str = Field(
        ...,
        description="The final response generated by the agent based on the users query and context",
    )


class SQLJudgementSchema(BaseModel):
    judgement: Literal["Yes", "No"] = Field(
        ...,
        description="Judgement within the sql query wheather the sql query is safe to run or not",
    )
    comments: str = Field(
        ...,
        description="Additional comments or feedbacks from the judge regarding the sql query",
    )
